const run = async (
  command: string,
  args: string[],
  options?: { input?: string }
) =>
  new Promise<{ stderr: string; stdout: string }>((resolve, reject) => {
    const child = spawn(command, args, {
      cwd: widgetRoot,
      stdio: ["pipe", "pipe", "pipe"],
    });

    let stdout = "";
    let stderr = "";

    child.stdout.setEncoding("utf8");
    child.stderr.setEncoding("utf8");

    child.stdout.on("data", (chunk) => {
      stdout += chunk;
    });
    child.stderr.on("data", (chunk) => {
      stderr += chunk;
    });
    child.on("error", reject);
    child.on("close", (code) => {
      if (code === 0) {
        resolve({ stdout, stderr });
        return;
      }

      reject(
        new Error(
          [
            `Command failed: ${command} ${args.join(" ")}`,
            `Exit code: ${code}`,
            stderr.trim(),
          ]
            .filter(Boolean)
            .join("\n")
        )
      );
    });

    if (options?.input) {
      child.stdin.write(options.input);
    }
    child.stdin.end();
  });

const fetchSpec = async (spec: SpecConfig) => {
  const response = await fetch(spec.url);

  if (!response.ok) {
    throw new Error(
      `Failed to fetch ${spec.name} spec from ${spec.url}: ${response.status} ${response.statusText}`
    );
  }

  return response.text();
};

/**
 * In Effect rc.115, openapigen emits `Schema.StructWithRest` for OpenAPI objects
 * that omit `additionalProperties`. Explicitly closing objects that declare
 * `properties` ensures openapigen emits `Schema.Struct`, preserving direct
 * `.fields` access across widget domain models.
 */
const closeOpenApiObjectSchemas = (document: unknown): void => {
  const isJsonObject = (value: unknown): value is Record<string, unknown> =>
    typeof value === "object" && value !== null && !Array.isArray(value);

  const visit = (value: unknown): void => {
    if (Array.isArray(value)) {
      for (const item of value) visit(item);
      return;
    }
    if (!isJsonObject(value)) return;

    if (
      value.type === "object" &&
      value.additionalProperties === undefined &&
      isJsonObject(value.properties)
    ) {
      value.additionalProperties = false;
    }

    for (const child of Object.values(value)) visit(child);
  };

  visit(document);
};

const prepareSpecDocument = (spec: SpecConfig, contents: string) => {
  const document = parse(spec.prepareSpec?.(contents) ?? contents) as unknown;
  pruneOpenApiDocument(document, spec.prune);
  normalizeOpenApiUnionObjects(document);
  closeOpenApiObjectSchemas(document);
  return document;
};

const serializeSpecDocument = (spec: SpecConfig, document: unknown) =>
  spec.specFileName.endsWith(".json")
    ? `${JSON.stringify(document, null, 2)}\n`
    : // openapigen's YAML parser rejects folded plain scalars, so keep every
      // scalar on a single line instead of wrapping at the default width.
      stringify(document, { lineWidth: 0 });

const extractSchemaOnlyOutput = (output: string, specName: string) => {
  const clientMarker = "\nexport interface OperationConfig {";
  const clientStart = output.indexOf(clientMarker);

  if (clientStart === -1) {
    throw new Error(
      `${specName} schema generation did not contain the expected client marker`
    );
  }

  return `${output
    .slice(0, clientStart)
    .replace(/^import \* as Data from "effect\/Data";?\r?\n/m, "")
    .replace(/^import \* as Effect from "effect\/Effect";?\r?\n/m, "")
    .replace(/^import type \{ SchemaError \} from "effect\/Schema";?\r?\n/m, "")
    .replace(
      /^import(?: type)? \* as HttpClient[^\n]+"effect\/http\/[^\n]+\r?\n/gm,
      ""
    )
    .trimEnd()}\n`;
};

const generateSpec = async (spec: SpecConfig, tempDir: string) => {
  const specPath = path.join(tempDir, spec.specFileName);
  const schemaSpecPath = path.join(tempDir, `schema-${spec.specFileName}`);
  const patchPath = path.join(tempDir, `${spec.specFileName}.patch.json`);
  const extraSchemas = spec.prune.extraSchemas ?? [];

  console.log(`Fetching ${spec.name} spec from ${spec.url}`);
  const document = prepareSpecDocument(spec, await fetchSpec(spec));
  await writeFile(specPath, serializeSpecDocument(spec, document));
  await writeFile(
    schemaSpecPath,
    serializeSpecDocument(spec, withExtraSchemaRoots(document, extraSchemas))
  );
  await writeFile(patchPath, `${JSON.stringify(spec.patches, null, 2)}\n`);

  for (const output of spec.outputs) {
    await mkdir(path.dirname(output.outputPath), { recursive: true });

    console.log(
      `Generating ${path.relative(widgetRoot, output.outputPath)} (${output.format})`
    );
    const { stdout, stderr } = await run(openApiGeneratorBin, [
      "--spec",
      output.schemaOnly ? schemaSpecPath : specPath,
      "--name",
      spec.name,
      "--format",
      output.format,
      "--patch",
      patchPath,
    ]);

    if (stderr.trim()) {
      console.warn(stderr.trim());
    }

    if (!stdout.trim()) {
      throw new Error(
        `${spec.name} ${output.format} generation produced empty output`
      );
    }

    const generatedOutput = output.schemaOnly
      ? stripExtraSchemaRoots(
          extractSchemaOnlyOutput(stdout, spec.name),
          extraSchemas
        )
      : normalizeGeneratedTypeOnlySource(stdout);

    if (output.schemaOnly) {
      const issues = findUnsafeGeneratedSchemaUnions(
        generatedOutput,
        path.relative(widgetRoot, output.outputPath)
      );
      if (issues.length > 0) {
        throw new Error(
          `${spec.name} generated unsafe schema unions:\n${issues
            .map((issue) => `${issue.line}:${issue.column} ${issue.message}`)
            .join("\n")}`
        );
      }
    }

    await writeFile(
      output.outputPath,
      `${generatedFileHeader}${generatedOutput}`
    );
  }
};

const main = async () => {
  const requestedSpecs = new Set(process.argv.slice(2));
  const selectedSpecs = requestedSpecs.size
    ? specs.filter((spec) => requestedSpecs.has(spec.name))
    : specs;

  if (!selectedSpecs.length) {
    throw new Error(
      `No OpenAPI specs matched: ${[...requestedSpecs].join(", ")}`
    );
  }

  const tempDir = await mkdtemp(path.join(tmpdir(), "stakekit-openapi-"));
  try {
    for (const spec of selectedSpecs) {
      await generateSpec(spec, tempDir);
    }

    await run(biomeBin, [
      "check",
      "--write",
      "--unsafe",
      ...selectedSpecs.flatMap((spec) =>
        spec.outputs.map((output) =>
          path.relative(widgetRoot, output.outputPath)
        )
      ),
    ]);
  } finally {
    await rm(tempDir, { force: true, recursive: true });
  }

  await assertGeneratedSchemasSafe();
};

main().catch((error: unknown) => {
  console.error(error);
  process.exitCode = 1;
});
