type JsonPatchOperation = {
  op: "replace";
  path: string;
  value: unknown;
};

const nullableScalarPatch = ({
  description,
  example,
  property,
  schema,
  type,
}: {
  description: string;
  example: unknown;
  property: string;
  schema: string;
  type: "number" | "string";
}): JsonPatchOperation => ({
  op: "replace",
  path: `/components/schemas/${schema}/properties/${property}`,
  value: { description, example, nullable: true, type },
});

type SpecOutputConfig = {
  format: "httpclient" | "httpclient-type-only";
  outputPath: string;
  schemaOnly?: boolean;
};

