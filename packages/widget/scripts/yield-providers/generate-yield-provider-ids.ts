/**
 * Regenerates `src/generated/yield-provider-ids.ts` from the backend's yield
 * provider enum, the source of a yield's `providerId`.
 *
 * Run via `pnpm gen:yield-providers --source <enum file>`, or set
 * `YIELD_PROVIDERS_ENUM_PATH`. The source is a local file outside this
 * repository, so the path is never stored here.
 */
import { spawn } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { parseArgs } from "node:util";
import ts from "typescript";
import { repositoryRoot, widgetRoot } from "../paths";

const outputPath = path.join(widgetRoot, "src/generated/yield-provider-ids.ts");
const biomeBin = path.join(
  repositoryRoot,
  "node_modules/.bin",
  `biome${process.platform === "win32" ? ".CMD" : ""}`
);

type ProviderMember = { readonly name: string; readonly value: string };

const resolveSourcePath = () => {
  const { values } = parseArgs({ options: { source: { type: "string" } } });
  const source = values.source ?? process.env.YIELD_PROVIDERS_ENUM_PATH;
  if (!source) {
    throw new Error(
      "Pass the backend yield provider enum file with --source <path> or YIELD_PROVIDERS_ENUM_PATH."
    );
  }
  return path.resolve(source);
};

const readProviderMembers = (
  sourcePath: string,
  contents: string
): ReadonlyArray<ProviderMember> => {
  const sourceFile = ts.createSourceFile(
    sourcePath,
    contents,
    ts.ScriptTarget.Latest,
    true
  );
  const enums = sourceFile.statements.filter(
    (statement): statement is ts.EnumDeclaration =>
      ts.isEnumDeclaration(statement) &&
      !!statement.modifiers?.some(
        (modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword
      )
  );
  const [declaration] = enums;
  if (enums.length !== 1 || !declaration) {
    throw new Error(
      `${sourcePath} must export exactly one enum; found ${enums.length}.`
    );
  }

  const members = declaration.members.map((member) => {
    const { initializer, name } = member;
    if (!ts.isIdentifier(name) || !initializer) {
      throw new Error(
        `${declaration.name.text} member ${name.getText(sourceFile)} needs an identifier name and a value.`
      );
    }
    if (!ts.isStringLiteral(initializer)) {
      throw new Error(
        `${declaration.name.text}.${name.text} must be a string literal.`
      );
    }
    return { name: name.text, value: initializer.text };
  });

  const seen = new Set<string>();
  for (const { name, value } of members) {
    if (seen.has(value)) {
      throw new Error(`${declaration.name.text}.${name} repeats "${value}".`);
    }
    seen.add(value);
  }
  if (members.length === 0) {
    throw new Error(`${declaration.name.text} has no members.`);
  }

  return members;
};

const renderModule = (members: ReadonlyArray<ProviderMember>) =>
  [
    "// Generated by scripts/yield-providers/generate-yield-provider-ids.ts; do not edit.",
    "",
    "/** Yield provider IDs, as the Yield API reports a yield's `providerId`. */",
    "export const YieldProviderId = {",
    ...members.map(({ name, value }) => `  ${name}: ${JSON.stringify(value)},`),
    "} as const;",
    "",
    "export type YieldProviderId =",
    "  (typeof YieldProviderId)[keyof typeof YieldProviderId];",
    "",
  ].join("\n");

const formatOutput = () =>
  new Promise<void>((resolve, reject) => {
    const child = spawn(
      biomeBin,
      ["check", "--write", path.relative(widgetRoot, outputPath)],
      { cwd: widgetRoot, stdio: "inherit" }
    );
    child.on("error", reject);
    child.on("exit", (code) =>
      code === 0 ? resolve() : reject(new Error(`biome exited with ${code}`))
    );
  });

const sourcePath = resolveSourcePath();
const members = readProviderMembers(
  sourcePath,
  await readFile(sourcePath, "utf8")
);
await writeFile(outputPath, renderModule(members));
await formatOutput();
console.log(
  `Wrote ${members.length} yield provider IDs to ${path.relative(widgetRoot, outputPath)}`
);
