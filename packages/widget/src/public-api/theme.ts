type CompleteThemeNode<Node> = Node extends string
  ? string
  : {
      readonly [Key in keyof Node]: CompleteThemeNode<Node[Key]>;
    };

type PartialThemeNode<Node> = Node extends string
  ? string
  : {
      readonly [Key in keyof Node]?: PartialThemeNode<Node[Key]>;
    };

